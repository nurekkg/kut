// Минимальный service worker. Он нужен, чтобы приложение можно было установить на главный экран,
// и сознательно ничего не кэширует: запросы идут в сеть как обычно. Офлайн-оболочка и фоновая
// отправка очереди - вторая волна (ТЗ: «без offline-first»). Очередь отправки фактов уже живёт в
// самой странице (IndexedDB) и не зависит от этого файла.
self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

// Обработчик нужен для проверки «устанавливаемости» в части браузеров; сеть не подменяет.
self.addEventListener("fetch", () => {});
